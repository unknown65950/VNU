#!/bin/sh
# Bash trampoline: /usr/bin/env is missing on some hosts (e.g. Termux
# without termux-exec) -- if not under bash already, re-exec via PATH.
if [ -z "${BASH_VERSION:-}" ]; then exec env bash "$0" "$@"; fi
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_DIR="$ROOT_DIR/kernel"
SEED_DIR="$ROOT_DIR/grub-seed"
REPO_DIR="$(cd "$ROOT_DIR/.." && pwd)"

# The architecture is the directory under kernel/arch/ to build: given as
# ARCH=<name> on the command line (or in the environment), i386 by default.
ARCH="${ARCH:-i386}"
for _arg in "$@"; do
    case "$_arg" in ARCH=*) ARCH="${_arg#ARCH=}" ;; esac
done
if [[ ! -d "$SOURCE_DIR/arch/$ARCH" ]]; then
    _ports=""
    for _d in "$SOURCE_DIR"/arch/*/; do
        [[ -d "$_d" ]] && _ports+="$(basename "$_d") "
    done
    echo "build_iso.sh: unknown architecture '$ARCH'" >&2
    echo "  available: ${_ports% }" >&2
    exit 2
fi

# i386 keeps the historic build tree and image name (the README, the test
# suite and `vnu install` all say kernel/build and vnu.iso); every other
# port gets its own pair so two architectures can coexist on one host.
if [[ "$ARCH" == i386 ]]; then
    BUILD_DIR="$ROOT_DIR/kernel/build"
    OUT_ISO="$ROOT_DIR/vnu.iso"
else
    BUILD_DIR="$ROOT_DIR/kernel/build-$ARCH"
    OUT_ISO="$ROOT_DIR/vnu-$ARCH.iso"
fi

# The kernel embeds every userspace binary via generated
# vnu/kernel/proc/embedded_*.h (gitignored build artifacts produced by
# tools/build_userspace.sh). A fresh checkout has none of them yet, so run
# the userspace build first; afterwards the headers exist and this step is
# skipped, keeping incremental rebuilds fast.
if ! ls "$ROOT_DIR"/kernel/proc/embedded_*.h >/dev/null 2>&1; then
    echo "no embedded_*.h yet, building userspace..."
    bash "$REPO_DIR/tools/build_userspace.sh"
fi

# CMake stores absolute source/build paths in CMakeCache.txt. A build
# directory copied from another machine/archive must be reconfigured.
if [[ -f "$BUILD_DIR/CMakeCache.txt" ]]; then
    cached_home="$(sed -n 's|^CMAKE_HOME_DIRECTORY:INTERNAL=||p' "$BUILD_DIR/CMakeCache.txt" | head -n1 || true)"
    if [[ -n "$cached_home" && "$cached_home" != "$SOURCE_DIR" ]]; then
        echo "CMake cache belongs to: $cached_home"
        echo "Current source tree is: $SOURCE_DIR"
        echo "Removing stale build cache..."
        rm -rf "$BUILD_DIR"
    fi
fi

cmake -S "$SOURCE_DIR" -B "$BUILD_DIR" -DVNU_KERNEL_ARCH="$ARCH"
cmake --build "$BUILD_DIR" -j"$(nproc 2>/dev/null || echo 1)"

# Stage the ISO payload: kernel, grub.cfg and (for the portable path) the
# GRUB El Torito boot image + modules, so the staging dir mirrors what
# grub-mkrescue would produce.
mkdir -p "$ROOT_DIR/iso/boot/grub"
cp "$BUILD_DIR/kernel.elf" "$ROOT_DIR/iso/boot/kernel.elf"

# The initial ramdisk: vnu/initrd/ packed into a ustar archive and
# loaded as a second Multiboot2 module (the kernel file itself is the
# first, which is how `vnu install` copies the running kernel). The
# kernel unpacks it into /initrd at boot; see vnu/kernel/proc/initrd.cpp.
bash "$REPO_DIR/tools/build_initrd.sh"
cp "$ROOT_DIR/initrd.tar" "$ROOT_DIR/iso/boot/initrd.tar"

cat > "$ROOT_DIR/iso/boot/grub/grub.cfg" <<'EOF'
set timeout=0
set default=0
menuentry "VNU" {
    multiboot2 /boot/kernel.elf
    module2 /boot/kernel.elf
    module2 /boot/initrd.tar
    boot
}
EOF

# GRUB stage files for the ISO boot image come from the SEED_DIR: a copy of
# /boot/grub/i386-pc + /efi.img from a grub-mkrescue-produced ISO (they are
# spec-agnostic bootloader blobs, not build output of this tree). The seed
# is (re)generated by pulling those files out of an existing vnu.iso; a
# machine that has grub-mkrescue never needs the seed at all.
ensure_grub_seed() {
    if [[ -f "$SEED_DIR/i386-pc/eltorito.img" && -f "$SEED_DIR/efi.img" ]]; then
        return 0
    fi
    if [[ ! -f "$ROOT_DIR/vnu.iso" ]]; then
        echo "no grub-mkrescue and no vnu.iso to take the GRUB-ready boot" >&2
        echo "files from (eltorito.img + modules + efi.img)." >&2
        echo "Options: build the ISO once on a machine that has grub-mkrescue," >&2
        echo "or drop a finished vnu.iso next to this script." >&2
        exit 1
    fi
    echo "extracting the GRUB boot blobs from vnu.iso -> $SEED_DIR ..."
    rm -rf "$SEED_DIR"
    mkdir -p "$SEED_DIR"
    xorriso -osirrox on -indev "$ROOT_DIR/vnu.iso" \
        -extract /boot/grub/i386-pc "$SEED_DIR/i386-pc" >/dev/null
    xorriso -osirrox on -indev "$ROOT_DIR/vnu.iso" \
        -extract /efi.img "$SEED_DIR/efi.img" >/dev/null
    chmod -R u+rwX "$SEED_DIR"
}

# Portable ISO builder: reproduces what grub-mkrescue does with xorriso,
# using the pre-built GRUB blobs from the seed. Used on hosts where the
# grub tools are not installed (e.g. Termux).
build_iso_portable() {
    ensure_grub_seed

    chmod -R u+rwX "$ROOT_DIR/iso" 2>/dev/null || true
    rm -rf "$ROOT_DIR/iso/boot/grub/i386-pc" "$ROOT_DIR/iso/efi.img"
    cp -a "$SEED_DIR/i386-pc" "$ROOT_DIR/iso/boot/grub/i386-pc"
    cp -a "$SEED_DIR/efi.img" "$ROOT_DIR/iso/efi.img"

    xorriso -as mkisofs \
        -V ISOIMAGE \
        -b boot/grub/i386-pc/eltorito.img \
        -no-emul-boot \
        -boot-load-size 4 \
        -boot-info-table \
        --grub2-boot-info \
        -eltorito-alt-boot \
        -e efi.img \
        -no-emul-boot \
        -boot-load-size 5760 \
        -o "$OUT_ISO" "$ROOT_DIR/iso"
}

if command -v grub-mkrescue >/dev/null 2>&1; then
    grub-mkrescue -o "$OUT_ISO" "$ROOT_DIR/iso"
else
    build_iso_portable
fi
echo "done: $OUT_ISO"
