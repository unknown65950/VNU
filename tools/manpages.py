#!/usr/bin/env python3
"""Embed the system manual pages into the kernel image.

A manual page is one plain-text file in vnu/userspace/man/pages/, named
after the command it documents. The build installs each at
/etc/vnu/manpages/<name>, where `man <name>` reads it (see
vnu/userspace/man/man.c), so adding a command's page is dropping a file
in that directory: nothing in the kernel and nothing in the man binary is
edited to add one. That is the rule in AGENTS.md.

    python3 tools/manpages.py status     list the pages and their sizes
    python3 tools/manpages.py generate   write vnu/kernel/proc/embedded_manpages.h

`generate` is what tools/build_userspace.sh calls, so `make iso` picks up
whatever is in pages/ with no separate step.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES_DIR = ROOT / "vnu" / "userspace" / "man" / "pages"
OUT = ROOT / "vnu" / "kernel" / "proc" / "embedded_manpages.h"


def read_pages():
    """(name, bytes) for every page file, sorted by name."""
    if not PAGES_DIR.is_dir():
        return []
    out = []
    for p in sorted(PAGES_DIR.iterdir()):
        if p.name.startswith(".") or not p.is_file():
            continue
        out.append((p.name, p.read_bytes()))
    return out


def sym(name):
    """A C identifier for a page name like `resolv.conf`."""
    return "".join(c if c.isalnum() else "_" for c in name)


def generate():
    items = read_pages()
    seen = {}
    for name, _ in items:
        s = sym(name)
        if s in seen:
            raise SystemExit("page names %s and %s share the symbol %s"
                             % (seen[s], name, s))
        seen[s] = name
    with OUT.open("w") as f:
        f.write("/* Generated by tools/manpages.py - do not edit.\n"
                " * One blob per file in vnu/userspace/man/pages/, mounted\n"
                " * at /etc/vnu/manpages/<name> by gui/apps.cpp. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct EmbeddedManPage {\n"
                "    const char* name;\n"
                "    const uint8_t* data;\n"
                "    uint32_t size;\n"
                "};\n\n")
        for name, data in items:
            f.write("static const uint8_t mp_%s[] = {\n" % sym(name))
            for i in range(0, len(data), 12):
                chunk = data[i:i + 12]
                f.write("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
            f.write("};\n\n")
        f.write("static const EmbeddedManPage embedded_manpages[] = {\n")
        for name, _ in items:
            f.write("    {\"%s\", mp_%s, sizeof(mp_%s)},\n"
                    % (name, sym(name), sym(name)))
        f.write("};\n\n")
        f.write("static const uint32_t embedded_manpages_count = %d;\n"
                % len(items))
    print("embedded %d manual pages (%d bytes)"
          % (len(items), sum(len(d) for _, d in items)))
    for name, data in items:
        if not data.endswith(b"\n"):
            print("warning: page %s does not end with a newline" % name,
                  file=sys.stderr)


def status():
    items = read_pages()
    for name, data in items:
        print("%-16s %6d bytes" % (name, len(data)))
    print("%d pages, %d bytes" % (len(items), sum(len(d) for _, d in items)))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("command", choices=("status", "generate"),
                    help="what to do")
    args = ap.parse_args()
    if args.command == "status":
        status()
    else:
        generate()


if __name__ == "__main__":
    main()
